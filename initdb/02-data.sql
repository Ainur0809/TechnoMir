-- Сумма заказа = сумма позиций. У заказа 20 позиций нет — total остаётся 0.
UPDATE orders o
SET total = s.sum_total
FROM (
    SELECT order_id, SUM(quantity * unit_price) AS sum_total
    FROM order_items
    GROUP BY order_id
) s
WHERE s.order_id = o.id;

