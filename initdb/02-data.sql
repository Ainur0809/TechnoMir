SET total = s.sum_total
FROM (
    SELECT order_id, SUM(quantity * unit_price) AS sum_total
    FROM order_items
    GROUP BY order_id
) s
WHERE s.order_id = o.id;

-- Заказ 13: промокод на 1 000 — total расходится с суммой позиций (пригодится в 4.3.20).
UPDATE orders SET total = total - 1000.00 WHERE id = 13;

